import { expect, test } from './fixtures.ts';

test('create project, load demo, close it, open project G-code through Files, then reverse the order', async ({ page }, testInfo) => {
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('data-ready', 'true');
  const job = page.locator('[data-screen="job"]');
  const projects = page.locator('[data-screen="projects"]');
  const rail = page.locator('[data-region="rail"]');
  await rail.locator('[data-view="projects"]').click();
  await projects.locator('[data-action="project-new"]').click();
  await projects.locator('[data-project="file-input"]').setInputFiles({ name: 'plate.nc', mimeType: 'text/plain', buffer: Buffer.from('G21 G90\nG0 X12 Y8\nM2\n') });
  await expect(projects.locator('[data-project-file="plate.nc"]')).toBeVisible();
  await rail.locator('[data-view="job"]').click();
  await job.locator('[data-job-step="place"]').click();
  await job.locator('[data-sample="test-square"]').click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('test-square.nc');
  await job.locator('[data-action="job-close"]').click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('none');
  await job.locator('[data-action="job-files"]').click();
  const drawer = job.locator('.job-files-drawer');
  await expect(drawer.getByLabel('Project files')).toHaveValue(/.+/);
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('project-files-drawer.png') });
  await drawer.getByRole('button', { name: 'Open as the job', exact: true }).click();
  await expect(drawer).toBeHidden();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('plate.nc');
  await job.locator('[data-action="job-close"]').click();
  await job.locator('[data-job-step="place"]').click();
  await job.locator('[data-sample="test-square"]').click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('test-square.nc');
  // Switching directly also works; closing first is optional.
  await job.locator('[data-action="job-files"]').click();
  await drawer.getByRole('button', { name: 'Open as the job', exact: true }).click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('plate.nc');
  await rail.locator('[data-view="projects"]').click();
  await expect(projects.locator('[data-project-file="plate.nc"]')).toBeVisible();
  await expect(projects.locator('[data-project-job]')).toHaveCount(1);
});

test('a project opens over the demo, closes without deleting files, and reopens its saved job', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('data-ready', 'true');
  const job = page.locator('[data-screen="job"]');
  const projects = page.locator('[data-screen="projects"]');
  const openProject = job.locator('.job-actions [data-action="job-projects"]');
  await job.locator('[data-job-step="place"]').click();
  await job.locator('[data-sample="test-square"]').click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('test-square.nc');
  await expect(openProject).toHaveText('Open project');
  await openProject.click();
  await projects.locator('[data-action="project-new"]').click();
  await projects.locator('[data-project="file-input"]').setInputFiles({ name: 'bracket.cnc', mimeType: 'text/plain', buffer: Buffer.from('G21 G90\nG0 X12 Y8\nM2\n') });
  await expect(projects.locator('[data-project-file="bracket.cnc"] [data-project="file-role"]')).toHaveValue('gcode');
  const open = projects.locator('[data-action="project-open"]');
  await expect(open).toBeEnabled();
  await expect(open).toBeInViewport();
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('project-open-1280.png') });
  await open.click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('bracket.cnc');
  await expect(job.locator('[data-job="project"]')).toContainText('Project 1');
  await job.locator('[data-action="job-close"]').click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('none');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-ready', 'true');
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('none');
  await job.locator('[data-job-step="run"]').click();
  await expect(job.locator('[data-action="start-job"]')).toBeDisabled();
  await openProject.click();
  await expect(projects.locator('[data-project-file="bracket.cnc"]')).toBeVisible();
  await expect(projects.locator('[data-project-job]')).toHaveCount(1);
  await open.click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('bracket.cnc');
  await openProject.click();
  await expect(projects.locator('[data-project-job]')).toHaveCount(1);
  // Previously saved .cnc uploads were classified as Other. They remain openable.
  await projects.locator('[data-project-file="bracket.cnc"] [data-project="file-role"]').selectOption('other');
  await expect(projects.locator('[data-project-file="bracket.cnc"] [data-action="project-open-in-run"]')).toBeVisible();
  await projects.locator('[data-project="file-input"]').setInputFiles({ name: 'second.nc', mimeType: 'text/plain', buffer: Buffer.from('G21 G90\nG0 X24 Y16\nM2\n') });
  const picker = projects.locator('[data-project="open-file"]');
  await expect(picker.locator('option')).toHaveCount(2);
  await picker.selectOption({ label: 'second.nc' });
  await open.click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('second.nc');
  await openProject.click();
  await picker.selectOption({ label: 'bracket.cnc' });
  await page.setViewportSize({ width: 390, height: 844 });
  await open.scrollIntoViewIfNeeded();
  await expect(open).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('project-open-390.png') });
  await open.click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('bracket.cnc');
});

test('opening project G-code applies recorded Hardwood and asks before replacing an existing plan', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('data-ready', 'true');
  const rail = page.locator('[data-region="rail"]');
  const projects = page.locator('[data-screen="projects"]');
  const job = page.locator('[data-screen="job"]');
  await job.locator('[data-job-step="place"]').click();
  await job.locator('[data-sample="test-square"]').click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('test-square.nc');
  await rail.locator('[data-view="projects"]').click();
  await projects.locator('[data-action="project-new"]').click();
  await projects.locator('[data-project="file-input"]').setInputFiles({ name: 'hardwood.nc', mimeType: 'text/plain', buffer: Buffer.from('G21 G90\nG0 X12 Y8\nM2\n') });
  await projects.getByLabel('Material', { exact: true }).selectOption('builtin.hardwood');
  await projects.locator('[data-action="project-use-stock"]').click();
  await projects.locator('[data-action="project-open"]').click();
  const choice = page.getByRole('alertdialog', { name: 'Choose the setup' });
  await expect(choice).toContainText('Hardwood');
  await expect(choice.getByRole('button', { name: "Use the project's setup" })).toBeFocused();
  await choice.getByRole('button', { name: "Use the project's setup" }).click();
  await expect(job.locator('[data-preview="file-name"]')).toHaveText('hardwood.nc');
  await job.locator('[data-job-step="stock"]').click();
  await expect(job.locator('[data-setup-section="stock"]').getByRole('combobox')).toHaveValue('builtin.hardwood');
  await job.locator('[data-setup-section="stock"]').getByRole('combobox').scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('project-hardwood.png') });
  await job.getByRole('tab', { name: /^Notes/ }).click();
  await expect(job.locator('[data-notes="list"]')).toContainText('From project Project 1: Hardwood (oak, maple), Block 180 × 120 × 6.35 mm.');
  await page.screenshot({ path: testInfo.outputPath('project-setup-note.png') });
});
