// Regenerate with: node tools/catalog/generate-onsrud.mjs (no network).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source = JSON.parse(readFileSync(new URL('./onsrud-source.json', import.meta.url), 'utf8'));
const tools = source.map(t => ({
  id: `catalog.onsrud.${t.part_number.toLowerCase()}`, version: 1, name: '',
  type: t.tool_type.includes('Ball nose') ? 'ball' : t.tool_type.includes('O-flute') ? 'o-flute' : 'flat',
  geometry: {
    diameter: t.cutting_diameter_decimal_in * 25.4,
    shank: t.shank_diameter_decimal_in * 25.4,
    fluteLength: t.length_of_cut_decimal_in * 25.4,
    overallLength: t.overall_length_decimal_in * 25.4, flutes: t.flutes,
    ...(t.helix_angle === null ? {} : { helix: Number(t.helix_angle.match(/[0-9]+/)[0]) }),
  },
  toolMaterial: 'carbide', coating: 'uncoated', manufacturer: 'Onsrud', partNumber: t.part_number,
  description: t.tool_type,
  notes: `${t.cut_direction}. Source dimensions (in): diameter ${t.cutting_diameter_in}; shank ${t.shank_diameter_in}; flute length ${t.length_of_cut_in}; overall ${t.overall_length_in}. Helix: ${t.helix_angle ?? 'not published'}. ${t.notes.join(' ')}`,
  purchase: [{ vendor: 'Onsrud', url: t.source, sku: t.part_number, kind: 'link' }],
  cuttingData: t.cutting_data.map(c => ({
    materialRef: { id: `onsrud.${c.material.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`, version: 1 },
    materialName: c.material, fz: c.chipload_min_in * 25.4, fzMax: c.chipload_max_in * 25.4, source: 'manufacturer',
    sourceUrl: c.source, sourcePage: c.pdf_page,
    note: c.notes.some(n => n.includes('Possible layout issue')) ? 'Check the catalog: this value may be misprinted' : '',
  })),
  life: { minutes: 0, byMaterial: [] }, tags: [], images: [],
}));
const version = createHash('sha256').update(JSON.stringify(tools)).digest('hex');
writeFileSync(new URL('../../workers/run/src/catalogData.ts', import.meta.url), `// Generated by tools/catalog/generate-onsrud.mjs. Worker-only public data.\nexport const CATALOG_VERSION = '${version}';\nexport const ONSRUD_CATALOG = ${JSON.stringify(tools, null, 2)} as const;\n`);
