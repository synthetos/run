/**
 * The P0-05 contrast table (ROADMAP P0-05 acceptance: "Contrast table for the
 * new tokens: at least 4.5:1 for text and 3:1 for non-text, in both themes";
 * RUN_PLAN §7.1).
 *
 * Every pair below is checked in both themes, with the token values read
 * from apps/web/src/styles/tokens.css. `renderTable()` writes
 * docs/design/contrast.md (`pnpm gen:contrast`); a test fails when a pair is
 * below its minimum or when the committed table is stale. Add a pair here
 * whenever a safety colour is used on a new background.
 */
import { contrast } from './wcag.ts';
import type { Themes, ThemeName } from './theme.ts';

export type Kind = 'text' | 'non-text';

/** WCAG 2.2 SC 1.4.3 (text, AA) and SC 1.4.11 (non-text). */
export const MINIMUM: Readonly<Record<Kind, number>> = { text: 4.5, 'non-text': 3 };

export interface Pair {
  /**
   * The foreground token. With several, the element shows all of them at its
   * edge (fill and border) and passes when the best one does.
   */
  readonly fg: string | readonly string[];
  readonly bg: string;
  readonly kind: Kind;
  readonly use: string;
}

const SAFETY_TOKENS = ['--danger', '--warn', '--live', '--state-run', '--state-hold', '--state-alarm'];

export const PAIRS: readonly Pair[] = [
  ...SAFETY_TOKENS.flatMap((t): Pair[] => [
    { fg: t, bg: '--sheet', kind: 'text', use: `${t} as text or icon on a sheet panel` },
    { fg: t, bg: '--paper', kind: 'text', use: `${t} as text or icon on the drafting paper` },
    { fg: t, bg: '--blue-wash', kind: 'text', use: `${t} as text on a selected (pencil-blue wash) row` },
  ]),
  { fg: '--tan', bg: '--sheet', kind: 'text', use: 'drafting accent (tan) as a section label on a sheet panel' },
  { fg: '--tan', bg: '--paper', kind: 'text', use: 'drafting accent (tan) as text on the drafting paper' },
  { fg: '--tan', bg: '--tan-wash', kind: 'text', use: 'drafting accent (tan) as text on its own wash (a secondary selection)' },
  { fg: '--ink', bg: '--tan-wash', kind: 'text', use: 'body text on the tan wash' },
  { fg: '--on-tan', bg: '--tan', kind: 'text', use: 'text on a solid tan fill' },
  { fg: '--bar-fg', bg: '--bar-bg', kind: 'text', use: 'safety bar text (W1, version chip)' },
  { fg: '--band-fg', bg: '--band-bg', kind: 'text', use: 'state band text (W7)' },
  { fg: '--band-fg', bg: '--band-hatch', kind: 'text', use: 'state band text over its hatch stripes' },
  { fg: '--on-stop', bg: '--stop-bg', kind: 'text', use: 'stop button label (W2)' },
  { fg: ['--bar-bg', '--hazard-dark'], bg: '--paper', kind: 'non-text', use: 'safety bar edge against the page (orange fill, black rule)' },
  { fg: ['--bar-bg', '--hazard-dark'], bg: '--sheet', kind: 'non-text', use: 'safety bar edge against a sheet panel' },
  { fg: '--hazard-dark', bg: '--hazard-light', kind: 'non-text', use: 'hazard stripes' },
  { fg: ['--band-bg', '--band-fg'], bg: '--bar-bg', kind: 'non-text', use: 'state band inside the bar (white fill, black border)' },
  { fg: '--stop-bg', bg: '--bar-bg', kind: 'non-text', use: 'stop button against the bar' },
  { fg: '--stop-mark', bg: '--stop-bg', kind: 'non-text', use: 'pause mark on the stop button' },
  { fg: '--bar-fg', bg: '--bar-bg', kind: 'non-text', use: 'focus ring inside the safety bar' },
];

export interface Row {
  readonly theme: ThemeName;
  readonly pair: Pair;
  /** The foreground token that decided the ratio. */
  readonly fg: string;
  readonly fgValue: string;
  readonly bgValue: string;
  readonly ratio: number;
  readonly pass: boolean;
}

function value(themes: Themes, theme: ThemeName, token: string): string {
  const v = themes[theme].get(token);
  if (v === undefined) throw new Error(`token ${token} is not defined in the ${theme} theme`);
  return v;
}

export function evaluate(themes: Themes): Row[] {
  const rows: Row[] = [];
  for (const theme of ['light', 'dark'] as const) {
    for (const pair of PAIRS) {
      const bgValue = value(themes, theme, pair.bg);
      const candidates = (typeof pair.fg === 'string' ? [pair.fg] : pair.fg).map((fg) => {
        const fgValue = value(themes, theme, fg);
        return { fg, fgValue, ratio: contrast(fgValue, bgValue) };
      });
      const best = candidates.reduce((a, b) => (b.ratio > a.ratio ? b : a));
      // Compare at the two decimals the table shows, so the table and the verdict always agree.
      const ratio = Math.floor(best.ratio * 100) / 100;
      rows.push({ theme, pair, fg: best.fg, fgValue: best.fgValue, bgValue, ratio, pass: ratio >= MINIMUM[pair.kind] });
    }
  }
  return rows;
}

export function renderTable(rows: readonly Row[]): string {
  const lines = [
    '# Contrast table: safety tokens (ROADMAP P0-05)',
    '',
    'GENERATED by `pnpm gen:contrast` from `apps/web/src/styles/tokens.css` and the',
    'pairs in `tools/gates/src/tokens/contrast.ts`. Do not edit: a test fails when',
    'this file is stale or any pair is below its minimum (WCAG 2.2: 4.5:1 for',
    'text, SC 1.4.3; 3:1 for non-text, SC 1.4.11). Ratios are rounded down.',
    '',
    'Where a row names two foreground tokens, the element shows both at its edge',
    '(a fill and a border); the better one is listed and decides the row.',
    '',
    '| Theme | Foreground | Background | Use | Kind | Ratio | Min | Pass |',
    '|---|---|---|---|---|---:|---:|---|',
  ];
  for (const r of rows) {
    lines.push(
      `| ${r.theme} | \`${r.fg}\` ${r.fgValue} | \`${r.pair.bg}\` ${r.bgValue} | ${r.pair.use} | ${r.pair.kind} | ${r.ratio.toFixed(2)} | ${MINIMUM[r.pair.kind].toFixed(1)} | ${r.pass ? 'yes' : '**NO**'} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}
