/**
 * The SVG export guard refuses external CSS and every other way an exported
 * SVG could load something when opened (P0-04 review, LOW: the guard claimed
 * to refuse external resources but accepted `<style>@import ...</style>`).
 *
 * brandSvgExport is a POSITIVE allowlist: known drawing elements, known
 * presentation attributes with plain values, the five predefined XML
 * entities, and nothing else (no style element or attribute, no url(), no
 * @import, no character references that could spell either, no comments,
 * CDATA or processing instructions).
 */
import { describe, expect, it } from 'vitest';
import { brandSvgExport, checkSvgExport, TrustedTypesError } from '../src/security/tt.ts';

const NS = 'xmlns="http://www.w3.org/2000/svg"';
const doc = (inner: string, attrs = ''): string => `<svg ${NS}${attrs}>${inner}</svg>`;

describe("the reviewer's reproductions", () => {
  it.each([
    ['@import with url()', '<style>@import url("https://example.invalid/tracker.css");</style>'],
    ['@import with a string', '<style>@import "https://external.invalid/style.css";</style>'],
  ])('refuses %s', (_label, inner) => {
    expect(() => brandSvgExport(doc(inner))).toThrow(TrustedTypesError);
  });
});

describe('external CSS and URL-bearing constructs', () => {
  it.each([
    ['a style element, even empty', '<style></style>'],
    ['a style element with a namespace prefix', '<svg:style>@import "x";</svg:style>'],
    ['a style element in upper case', '<STYLE>a{}</STYLE>'],
    ['a style attribute with url()', '<rect style="fill:url(https://x/p.svg#a)"/>'],
    ['a style attribute without url()', '<rect style="fill:red"/>'],
    ['a fill url()', '<rect fill="url(https://x/p.svg#a)"/>'],
    ['a fill url() with spaces and upper case', '<rect fill="URL ( https://x/p.svg#a )"/>'],
    ['a url() spelled with a decimal character reference', '<rect fill="&#117;rl(https://x/a)"/>'],
    ['a url() spelled with a hex character reference', '<rect fill="&#x75;rl(https://x/a)"/>'],
    ['a CSS escape in an attribute', '<rect fill="\\75 rl(https://x/a)"/>'],
    ['a filter reference', '<rect filter="url(#f)"/>'],
    ['a mask attribute', '<rect mask="m"/>'],
    ['a cursor attribute', '<rect cursor="pointer"/>'],
    ['an xlink:href', '<rect xlink:href="https://x"/>'],
    ['an xlink namespace declaration', '<g xmlns:xlink="http://www.w3.org/1999/xlink"/>'],
    ['an xml-stylesheet processing instruction', '<?xml-stylesheet href="https://x/s.css"?>'],
    ['a CDATA section', '<text><![CDATA[@import "x";]]></text>'],
    ['a comment', '<!-- hidden -->'],
    ['an unknown element', '<feImage/>'],
    ['a pattern element', '<pattern/>'],
    ['a font-face element', '<font-face/>'],
    ['an unquoted attribute', '<rect width=10/>'],
    ['an attribute with no value', '<rect hidden/>'],
    ['a stray ampersand', '<text>a & b</text>'],
    ['an unknown named entity', '<text>&nbsp;</text>'],
    ['a stray less-than inside an attribute', '<rect fill="<x"/>'],
    ['a malformed tag', '<rect / >'],
  ])('refuses %s', (_label, inner) => {
    expect(() => brandSvgExport(doc(inner))).toThrow(TrustedTypesError);
  });

  it('refuses a second, different namespace on the root, or extra root attributes it does not know', () => {
    expect(() => brandSvgExport(`<svg ${NS} xmlns:xlink="http://www.w3.org/1999/xlink"></svg>`)).toThrow(TrustedTypesError);
    expect(() => brandSvgExport(`<svg ${NS} style="background:url(https://x)"></svg>`)).toThrow(TrustedTypesError);
    expect(() => brandSvgExport('<svg xmlns="http://evil.invalid/ns" data-x="http://www.w3.org/2000/svg"></svg>')).toThrow(TrustedTypesError);
  });

  it('refuses content after the closing root tag, or a second root', () => {
    expect(() => brandSvgExport(`${doc('')}<style>@import "x";</style></svg>`)).toThrow(TrustedTypesError);
    expect(() => brandSvgExport(`${doc('')}${doc('')}`)).toThrow(TrustedTypesError);
  });
});

describe('what a wiring export needs still passes', () => {
  it('a diagram of shapes, paths and escaped labels', () => {
    const svg = doc(
      '<title>Wiring: X axis</title><desc>Generated by run</desc>' +
        '<g transform="translate(10 20)" fill="none" stroke="#1a1a1a" stroke-width="1.5">' +
        '<rect x="0" y="0" width="40" height="20" rx="2"/><circle cx="5" cy="5" r="2"/>' +
        '<path d="M0 0 L10 10 Z" stroke-linecap="round" stroke-dasharray="2 2"/>' +
        '<line x1="0" y1="0" x2="10" y2="10"/><polyline points="0,0 5,5"/><polygon points="0,0 5,5 0,5"/>' +
        '<ellipse cx="1" cy="1" rx="1" ry="2"/></g>' +
        '<text x="1" y="2" font-family="system-ui, sans-serif" font-size="12" text-anchor="middle">X+ &amp; Y- &lt;24 V&gt; &quot;M3&quot; &apos;A&apos;<tspan dy="1">2</tspan></text>',
      ' viewBox="0 0 100 50" width="100" height="50"',
    );
    const branded = brandSvgExport(svg);
    expect(checkSvgExport(branded)).toBe(svg);
  });

  it('a label may say url( or @import as text: text content is not CSS', () => {
    const svg = doc('<text>see url(x) and @import</text>');
    expect(checkSvgExport(brandSvgExport(svg))).toBe(svg);
  });
});
