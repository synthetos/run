/**
 * Validation and rendering of the behaviour register (RUN_PLAN §8.1: "a
 * generated STATUS.md lists the UNVERIFIED ones for the release checklist").
 *
 * `renderStatus()` is pure; `scripts/gen-status.ts` writes its output to
 * packages/testkit/STATUS.md and `test/honesty.test.ts` fails when the
 * committed file differs.
 */
import '../marker.ts';
import type { Behaviour, ModelLimit } from './types.ts';

/** Problems with the register; empty when it is well formed. */
export function validateBehaviours(behaviours: readonly Behaviour[]): string[] {
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const b of behaviours) {
    if (!/^(EN|TG)-[A-Z0-9-]+$/.test(b.id)) problems.push(`${b.id}: id must look like EN-... or TG-...`);
    if (seen.has(b.id)) problems.push(`${b.id}: duplicate id`);
    seen.add(b.id);
    if ((b.id.startsWith('EN-') ? 'tinyg-en' : 'tinyg-440') !== b.model) problems.push(`${b.id}: id prefix does not match model ${b.model}`);
    if (b.summary.trim().length < 10) problems.push(`${b.id}: summary too short`);
    if (b.cites.length === 0) problems.push(`${b.id}: no citation (every behaviour cites the firmware, even UNVERIFIED ones)`);
    if (b.status === 'UNVERIFIED' && (b.bench === undefined || b.bench.trim() === '')) problems.push(`${b.id}: UNVERIFIED needs the bench task that closes it`);
    if (b.status === 'verified-bench' && (b.bench === undefined || !/record/i.test(b.bench))) problems.push(`${b.id}: verified-bench needs the bench record`);
    for (const c of b.cites) {
      const [from, to] = c.lines;
      if (!(Number.isInteger(from) && Number.isInteger(to) && from >= 1 && to >= from)) problems.push(`${b.id}: bad line range ${from}-${to} in ${c.file}`);
      if (c.quote.trim() === '') problems.push(`${b.id}: empty quote for ${c.file}`);
      if (c.src === 'EN-HIL' ? !c.file.startsWith('tests/hil/') : c.file.startsWith('/') || c.file.includes('..')) problems.push(`${b.id}: bad path ${c.file}`);
      if (b.model === 'tinyg-440' && c.src === 'EN') problems.push(`${b.id}: a 440.21 behaviour cites edge-next source`);
      if (b.model === 'tinyg-en' && c.src === 'TG') problems.push(`${b.id}: an edge-next behaviour cites 440.21 source`);
    }
  }
  return problems;
}

const STATUS_ORDER = ['UNVERIFIED', 'verified-source', 'verified-bench'] as const;

function cite(c: Behaviour['cites'][number]): string {
  const range = c.lines[0] === c.lines[1] ? `${c.lines[0]}` : `${c.lines[0]}-${c.lines[1]}`;
  return `${c.src} ${c.file}:${range}`;
}

function row(b: Behaviour): string {
  const issues = b.issues !== undefined && b.issues.length > 0 ? ` (${b.issues.join(', ')})` : '';
  const bench = b.bench ?? '';
  return `| ${b.id} | ${b.status} | ${b.summary.replace(/\|/g, '\\|')}${issues} | ${b.cites.map(cite).join('; ')} | ${bench} |`;
}

/** The STATUS.md text. Deterministic: same register, same bytes. */
export function renderStatus(behaviours: readonly Behaviour[], limits: readonly ModelLimit[]): string {
  const sorted = (model: Behaviour['model']): Behaviour[] =>
    behaviours.filter((b) => b.model === model).sort((a, b) => STATUS_ORDER.indexOf(a.status) - STATUS_ORDER.indexOf(b.status) || a.id.localeCompare(b.id));
  const unverified = behaviours.filter((b) => b.status === 'UNVERIFIED').sort((a, b) => a.id.localeCompare(b.id));
  const head = '| Id | Status | Behaviour | Citation | Bench |\n|---|---|---|---|---|';
  const counts = STATUS_ORDER.map((s) => `${behaviours.filter((b) => b.status === s).length} ${s}`).join(', ');
  return [
    '# Test kit model status',
    '',
    '<!-- Generated by `pnpm --filter @synthetos/testkit gen:status` from src/honesty/behaviours.ts. Do not edit. -->',
    '',
    'DEV ONLY. The firmware models in this package exist for tests; they never ship (RUN_PLAN §8.1, T-S40).',
    'Every behaviour a safety claim depends on carries a citation at a pinned commit and a status',
    '(RUN_PLAN §8.1 honesty rule). Pins: EN = TinyG edge-next `ead63997`, TG = master `d0418390` (440.21),',
    'EN-HIL = edge-next `tests/hil/` (`vendor/firmware-pins.json`). EN and TG paths are under `firmware/tinyg/`.',
    '',
    `Totals: ${behaviours.length} behaviours (${counts}).`,
    '',
    '## UNVERIFIED (release checklist)',
    '',
    'Each must be bench-verified, or covered by a mitigation that does not depend on it, before the phase that relies on it ships.',
    '',
    ...(unverified.length === 0 ? ['None.'] : [head, ...unverified.map(row)]),
    '',
    '## TinyG edge-next (`TinyGEdgeNextModel`)',
    '',
    head,
    ...sorted('tinyg-en').map(row),
    '',
    '## TinyG 440.21 (`TinyG440Model`)',
    '',
    head,
    ...sorted('tinyg-440').map(row),
    '',
    '## Model limits',
    '',
    'Simplifications of the models. No safety claim may rest on them.',
    '',
    '| Id | Scope | Limit |',
    '|---|---|---|',
    ...limits.map((l) => `| ${l.id} | ${l.scope} | ${l.summary.replace(/\|/g, '\\|')} |`),
    '',
  ].join('\n');
}
